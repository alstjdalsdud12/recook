package com.springmvc.domain;

public class Solution {
    private int s_no;
    private int m_no;
    private String s_category;
    private String s_title;
    private String s_summary;
    private String s_content;
    private String s_image;
    private int s_hit;
    private String s_datetime;
    private String m_nickname;

    public int getS_no() { return s_no; }
    public void setS_no(int s_no) { this.s_no = s_no; }
    public int getM_no() { return m_no; }
    public void setM_no(int m_no) { this.m_no = m_no; }
    public String getS_category() { return s_category; }
    public void setS_category(String s_category) { this.s_category = s_category; }
    public String getS_title() { return s_title; }
    public void setS_title(String s_title) { this.s_title = s_title; }
    public String getS_summary() { return s_summary; }
    public void setS_summary(String s_summary) { this.s_summary = s_summary; }
    public String getS_content() { return s_content; }
    public void setS_content(String s_content) { this.s_content = s_content; }
    public String getS_image() { return s_image; }
    public void setS_image(String s_image) { this.s_image = s_image; }
    public int getS_hit() { return s_hit; }
    public void setS_hit(int s_hit) { this.s_hit = s_hit; }
    public String getS_datetime() { return s_datetime; }
    public void setS_datetime(String s_datetime) { this.s_datetime = s_datetime; }
    public String getM_nickname() { return m_nickname; }
    public void setM_nickname(String m_nickname) { this.m_nickname = m_nickname; }
}