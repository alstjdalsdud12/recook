package com.springmvc.domain;

public class Event {

    private int e_no;

    private String e_title;

    private String e_desc;

    private String e_period;

    private String e_reward;

    private String e_method;

    private String e_icon;

    private String e_badge;

    public int getE_no() {
        return e_no;
    }

    public void setE_no(int e_no) {
        this.e_no = e_no;
    }

    public String getE_title() {
        return e_title;
    }

    public void setE_title(String e_title) {
        this.e_title = e_title;
    }

    public String getE_desc() {
        return e_desc;
    }

    public void setE_desc(String e_desc) {
        this.e_desc = e_desc;
    }

    public String getE_period() {
        return e_period;
    }

    public void setE_period(String e_period) {
        this.e_period = e_period;
    }

    public String getE_reward() {
        return e_reward;
    }

    public void setE_reward(String e_reward) {
        this.e_reward = e_reward;
    }

    public String getE_method() {
        return e_method;
    }

    public void setE_method(String e_method) {
        this.e_method = e_method;
    }

    public String getE_icon() {
        return e_icon;
    }

    public void setE_icon(String e_icon) {
        this.e_icon = e_icon;
    }

    public String getE_badge() {
        return e_badge;
    }

    public void setE_badge(String e_badge) {
        this.e_badge = e_badge;
    }
}